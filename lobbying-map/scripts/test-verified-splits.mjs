import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {applyVerifiedSplits} from './data/verified-splits.mjs';
const read=p=>JSON.parse(gunzipSync(readFileSync(p)));
const before=read('research/directory-base.json.gz');
const after=read('public/data/directory-v3.json.gz');
assert.deepEqual([...new Set(after.companies.flatMap(c=>c.members))].sort(),[...new Set(before.companies.flatMap(c=>c.members))].sort());
const prudential=after.companies.find(c=>c.id==='36c4d95b871c31bf');
const plc=after.companies.find(c=>c.id==='906034fc535ec96b');
assert.deepEqual(prudential.members,['36c4d95b871c31bf']);
assert.deepEqual(prudential.aliases,['PRUDENTIAL']);
assert.equal(prudential.years['2026'],2);
assert.deepEqual(plc.members,['906034fc535ec96b']);
assert.deepEqual(plc.aliases,['PRUDENTIAL PLC']);
assert(!plc.years['2026']);
assert(Object.keys(plc.years).every(y=>Number(y)<=2005));
assert.equal(read('public/data/reports/36.json.gz')[prudential.id].length,72);
assert.equal(read('public/data/reports/90.json.gz')[plc.id].length,9);
const decisions=JSON.parse(readFileSync('research/verified-entity-splits.json'));
const broken=structuredClone(decisions);broken[0].children[1].members=[];
assert.throws(()=>applyVerifiedSplits(before.companies,broken,()=>[]),/preserve every member/);
console.log('Prudential histories separated; all original members and 81 filing links preserved; PLC excluded from 2026.');

const university = decisions.find(d=>d.source_id==='dee91f8b5e872db6');
const universityReports=read('public/data/reports/de.json.gz')[university.source_id];
const children=university.children.map(c=>after.companies.find(x=>x.id===c.id));
assert.deepEqual(children.flatMap(c=>c.filing_ids).sort(),universityReports.map(r=>r.id).sort());
assert.equal(new Set(children.flatMap(c=>c.filing_ids)).size,33);
assert.equal(children[0].filing_ids.length,5);
assert(children[0].years['2026']);
assert(children.slice(1).every(c=>!c.years['2026']));
const missing=structuredClone(decisions);missing.find(d=>d.mode==='filings').children[0].filing_ids.pop();
assert.throws(()=>applyVerifiedSplits(before.companies,missing,id=>read(`public/data/reports/${id.slice(0,2)}.json.gz`)[id]),/preserve every filing/);
console.log('Anderson partition preserves all 33 filings exactly once; only South Carolina appears in 2026.');
const hospital=decisions.find(d=>d.source_id==='458c8d30ab79005e');
const hospitalReports=read('public/data/reports/45.json.gz')[hospital.source_id];
const hospitalCards=hospital.children.map(c=>after.companies.find(x=>x.id===c.id));
assert.deepEqual(hospitalCards.flatMap(c=>c.filing_ids).sort(),hospitalReports.map(r=>r.id).sort());
assert.equal(hospitalCards[0].filing_ids.length,57);
assert.equal(hospitalCards[1].filing_ids.length,29);
assert(hospitalCards[0].years['2026']);
assert(!hospitalCards[1].years['2026']);
assert.equal(hospitalCards[0].profile.website,'https://www.cmhburke.org/');
console.log('Burke hospital isolated with 57 verified filings; all 86 original reports retained.');
const douglas=decisions.find(d=>d.source_id==='db32ea46ccd83520');
const countyCards=douglas.children.map(c=>after.companies.find(x=>x.id===c.id));
const countyReports=read('public/data/reports/db.json.gz')[douglas.source_id];
assert.deepEqual(countyCards.flatMap(c=>c.filing_ids).sort(),countyReports.map(r=>r.id).sort());
assert.equal(new Set(countyCards.flatMap(c=>c.filing_ids)).size,95);
const activeCounties=countyCards.filter(c=>c.years['2026']);
assert.deepEqual(activeCounties.map(c=>c.name).sort(),['Douglas County (Colorado)','Douglas County (Washington)']);
assert(activeCounties.every(c=>c.years['2026']===2));
assert(countyCards.filter(c=>!c.years['2026']).every(c=>c.filing_ids.every(id=>countyReports.find(r=>r.id===id).year!==2026)));
console.log('Douglas County retains all 95 filings once; Colorado and Washington each have two 2026 reports.');
